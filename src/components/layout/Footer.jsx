import { Mail } from 'lucide-react'
import { Container } from '@/components/layout/Container'
import { FacebookIcon, GithubIcon, LinkedinIcon, XIcon } from '@/components/ui/SocialIcons'
import { site } from '@/data/site'

// Verified social links, in the order they are shown. Every URL here was
// supplied or verified by the user — never a placeholder.
// Icons stay monochrome by default; on hover (and keyboard focus) each
// takes its brand colour — GitHub, X and email are monochrome, so they
// simply brighten to the foreground colour.
const SOCIALS = [
  { label: 'GitHub', href: site.links.github, Icon: GithubIcon, hover: 'hover:text-fg focus-visible:text-fg' },
  { label: 'LinkedIn', href: site.links.linkedin, Icon: LinkedinIcon, hover: 'hover:text-brand-linkedin focus-visible:text-brand-linkedin' },
  { label: 'X', href: site.links.x, Icon: XIcon, hover: 'hover:text-fg focus-visible:text-fg' },
  { label: 'Facebook', href: site.links.facebook, Icon: FacebookIcon, hover: 'hover:text-brand-facebook focus-visible:text-brand-facebook' },
  { label: 'Email', href: `mailto:${site.links.email}`, Icon: Mail, hover: 'hover:text-fg focus-visible:text-fg' },
]

/**
 * Professional footer (blueprint §06): wordmark, tagline, verified social
 * links plus the verified email address, and a copyright year generated by
 * the site — never a hardcoded year.
 */

// Generated once when the module loads, so the year is never hardcoded.
const YEAR = new Date().getFullYear()

export function Footer() {
  return (
    <footer className="border-t border-line py-12">
      <Container>
        <div className="flex flex-col gap-6 md:flex-row md:items-start md:justify-between">
          <div>
            <a href="#top" className="font-semibold tracking-wide text-fg">
              {site.wordmark}
            </a>
            <p className="mt-2 text-sm text-fg-secondary">{site.tagline}</p>
          </div>
          <ul className="flex items-center gap-2">
            {SOCIALS.map(({ label, href, Icon, hover }) => {
              // External profiles open in a new tab; the email link must not —
              // target="_blank" on a mailto: opens a blank tab in some browsers.
              const isExternal = href.startsWith('http')
              return (
                <li key={label}>
                  <a
                    href={href}
                    {...(isExternal ? { target: '_blank', rel: 'noreferrer' } : {})}
                    aria-label={label}
                    className={`flex size-10 items-center justify-center rounded-lg border border-line bg-surface text-fg-secondary transition-colors hover:border-fg-muted ${hover}`}
                  >
                    <Icon className="size-5" />
                  </a>
                </li>
              )
            })}
          </ul>
        </div>
        <div className="mt-10 flex flex-col gap-2 border-t border-line pt-6 text-meta text-fg-muted md:flex-row md:items-center md:justify-between">
          <p>© {YEAR} {site.name}</p>
          <p>Designed as a living record of research, engineering, and continuous learning.</p>
        </div>
      </Container>
    </footer>
  )
}
